; Restore the inactive scrolling map during VBlank; the static map stays visible.
SECTION "map_restore",ROM
BeginMapRestore:
; Caller owns the VBlank boundary. Preserve all LCDC bits except map selection.
XOR A,A
LD [MapRestoreColumn],A
LD [OldCameraTile],A
LDH [$FF43],A
LDH A,[$FF40]
AND A,$F7
LDH [$FF40],A
RET

RestoreMapPair:
LD A,[MapRestoreColumn]
CP A,32
RET NC
CALL RestoreColumn
LD A,[MapRestoreColumn]
INC A
LD [MapRestoreColumn],A
CALL RestoreColumn
LD A,[MapRestoreColumn]
INC A
LD [MapRestoreColumn],A
CP A,32
RET NZ
; Final column has reached VRAM before the new map is selected.
LDH A,[$FF40]
OR A,$08
LDH [$FF40],A
RET

RestoreColumn:
; A is a validated initial-view column0..31. Write exactly18 rows.
LD L,A
LD H,0
LD DE,WorldMap
ADD HL,DE
LD A,[MapRestoreColumn]
LD E,A
LD D,$9C
LD BC,96
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
ADD A,32
LD E,A
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
ADD A,32
LD E,A
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
ADD A,32
LD E,A
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
ADD A,32
LD E,A
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
ADD A,32
LD E,A
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
ADD A,32
LD E,A
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
ADD A,32
LD E,A
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
ADD A,32
LD E,A
INC D
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
ADD A,32
LD E,A
LD A,[HL]
LD [DE],A
ADD HL,BC
LD A,E
