; Build nine ordinary OAM entries in WRAM; this routine never touches VRAM.
SECTION "scene",ROM
PrepareScene:
LD DE,SceneBuffer
LD A,[PlayerX]
LD [ObjectX],A
LD A,[PlayerX+1]
LD [ObjectX+1],A
LD A,[PlayerY]
LD [ObjectY],A
LD A,[PlayerY+1]
LD [ObjectY+1],A
LD A,[Fell]
LD [SceneHidden],A
LD A,12
LD [SceneTile],A
CALL AppendScene
LD A,[EnemyX]
LD [ObjectX],A
LD A,[EnemyX+1]
LD [ObjectX+1],A
LD A,$80
LD [ObjectY],A
LD A,$07
LD [ObjectY+1],A
XOR A,A
LD [SceneHidden],A
LD A,16
LD [SceneTile],A
CALL AppendScene
LD A,$00
LD [ObjectX],A
LD A,$06
LD [ObjectX+1],A
LD A,$80
LD [ObjectY],A
LD A,$05
LD [ObjectY+1],A
LD A,[Collected]
AND A,1
LD [SceneHidden],A
LD A,18
LD [SceneTile],A
CALL AppendScene
LD A,$80
LD [ObjectX],A
LD A,$10
LD [ObjectX+1],A
LD A,$80
LD [ObjectY],A
LD A,$04
LD [ObjectY+1],A
LD A,[Collected]
AND A,2
LD [SceneHidden],A
LD A,18
LD [SceneTile],A
CALL AppendScene
LD A,$00
LD [ObjectX],A
LD A,$1D
LD [ObjectX+1],A
LD A,$80
LD [ObjectY],A
LD A,$05
LD [ObjectY+1],A
LD A,[Collected]
AND A,4
LD [SceneHidden],A
LD A,18
LD [SceneTile],A
CALL AppendScene
LD A,$00
LD [ObjectX],A
LD A,$29
LD [ObjectX+1],A
LD A,$00
LD [ObjectY],A
LD A,$05
LD [ObjectY+1],A
LD A,[Collected]
AND A,8
LD [SceneHidden],A
LD A,18
LD [SceneTile],A
CALL AppendScene
LD A,$00
LD [ObjectX],A
LD A,$2E
LD [ObjectX+1],A
LD A,$00
LD [ObjectY],A
LD A,$07
LD [ObjectY+1],A
XOR A,A
LD [SceneHidden],A
LD A,20
LD [SceneTile],A
CALL AppendScene
; Fixed HUD entries are screen-relative: score at144,0 and mode at72,0.
LD A,16
LD [DE],A
INC DE
LD A,152
LD [DE],A
INC DE
LD A,[Score]
ADD A,A
ADD A,22
LD [DE],A
INC DE
XOR A,A
LD [DE],A
INC DE
LD A,16
LD [DE],A
INC DE
LD A,80
LD [DE],A
INC DE
LD A,[GameMode]
ADD A,A
ADD A,32
LD [DE],A
INC DE
XOR A,A
LD [DE],A
RET

AppendScene:
; Signed floor and full-width camera subtraction precede OAM byte encoding.
LD A,[ObjectX]
LD L,A
LD A,[ObjectX+1]
LD H,A
CALL PixelFloor
LD A,[Camera]
LD C,A
LD A,[Camera+1]
LD B,A
LD A,L
SUB A,C
LD L,A
LD A,H
SBC A,B
LD H,A
OR A,A
JR Z,SceneXPositive
CP A,$FF
JR NZ,SceneOffscreen
LD A,L
CP A,249
JR C,SceneOffscreen
JR SceneXReady
SceneXPositive:
LD A,L
CP A,160
JR NC,SceneOffscreen
JR SceneXReady
SceneOffscreen:
LD A,1
LD [SceneHidden],A
SceneXReady:
LD A,L
ADD A,8
LD [SceneX],A
LD A,[ObjectY]
LD L,A
LD A,[ObjectY+1]
LD H,A
CALL PixelFloor
LD A,H
OR A,A
JR Z,SceneYPositive
CP A,$FF
JR NZ,SceneYHidden
LD A,L
CP A,241
JR C,SceneYHidden
JR SceneYReady
SceneYPositive:
LD A,L
CP A,144
JR C,SceneYReady
SceneYHidden:
LD A,1
LD [SceneHidden],A
SceneYReady:
LD A,[SceneHidden]
OR A,A
JR NZ,SceneHiddenY
LD A,L
ADD A,16
JR SceneStore
SceneHiddenY:
XOR A,A
SceneStore:
LD [DE],A
INC DE
LD A,[SceneX]
LD [DE],A
INC DE
LD A,[SceneTile]
LD [DE],A
INC DE
XOR A,A
LD [DE],A
INC DE
RET
